#!/usr/bin/env bash
# PreToolUse: block direct edits to secrets, generated, and tool-managed files.
set -uo pipefail
f=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty')
[ -n "$f" ] || exit 0
base=$(basename "$f")
reason=""
case "$base" in
  .env|.env.*)
    [[ "$base" == ".env-example" ]] || reason="$base holds local secrets (SBFF_HMAC_KEY, SBFF_TURNSTILE_SECRET). Edit .env-example instead, or ask the user to change .env." ;;
  go.sum)        reason="go.sum is managed by 'make tidy' — run that instead of editing it." ;;
  coverage.out)  reason="coverage.out is generated by 'make test-ci'." ;;
  .docker-digests) reason=".docker-digests is generated by 'make pin-base-images'." ;;
esac
case "$f" in */docs/swagger/*) reason="docs/swagger/ is generated by 'make swag' from handler annotations." ;; esac
if [ -n "$reason" ]; then
  echo "Blocked: $reason" >&2
  exit 2
fi
exit 0
